"""Logo artwork -> 1-bit bitmaps for the OLED: python3 tools/gen-logos.py [preview-dir]

Reads tools/logos/whs-wolverine.png (the Woodstock High School mascot) and
docs/logo.png (Maker Lab Kids), trims the white, fits each into its box
and thresholds it, and writes lib/logos.py: MONO_HLSB bytes the shows
blit straight into the framebuffer. With a preview dir, also writes a
PNG of each bitmap (4x) to look at.
"""
import os
import struct
import sys
import zlib

from PIL import Image, ImageOps

OUT = "lib/logos.py"
JOBS = [
    # name, source, box (w, h), what counts as ink, crop (fractions of the source, or None)
    ("WHS", "tools/logos/whs-wolverine.png", (100, 56), "wolverine", None),
    ("MLK", "docs/logo.png", (64, 64), "colour", (0, 0, 0.39, 1)),     # the gear, flask and rocket; not the words
]


def ink(im, mode):
  """A grey image of the artwork: 255 solid ink, 128 a 50% checker (the
  OLED's only grey), 0 off."""
  px = im.load()
  out = Image.new("L", im.size, 0)
  op = out.load()
  for y in range(im.size[1]):
    for x in range(im.size[0]):
      r, g, b = px[x, y][:3]
      lum = (r * 299 + g * 587 + b * 114) // 1000
      sat = max(r, g, b) - min(r, g, b)
      if mode == "wolverine":           # navy outline solid, the maroon fur a checker, white off
        v = 0 if lum >= 150 else (128 if r > b + 25 else 255)
      else:                             # the gear: blues and outlines solid, greens a checker,
        if lum < 90 or (b > r + 30 and b >= g):    # the grey ring and the light flask glass off
          v = 255
        elif g > r + 20 and g > b:
          v = 128
        else:
          v = 0
      op[x, y] = v
  return out


def fit(im, box, mode):
  """Trim the white, scale into the box, then classify every pixel."""
  bbox = ink(im, mode).point(lambda v: 255 if v else 0).getbbox()
  im = im.crop(bbox)
  w, h = im.size
  bw, bh = box
  s = min(bw / w, bh / h)
  im = im.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)
  grey = ink(im, mode)
  px = grey.load()
  for y in range(grey.size[1]):
    for x in range(grey.size[0]):
      if px[x, y] == 128:
        px[x, y] = 255 if (x + y) & 1 else 0
  return grey


def hlsb(mask):
  w, h = mask.size
  stride = (w + 7) // 8
  buf = bytearray(stride * h)
  px = mask.load()
  for y in range(h):
    for x in range(w):
      if px[x, y]:
        buf[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
  return w, h, bytes(buf)


def png(path, mask, scale=4):
  w, h = mask.size
  px = mask.load()
  raw = b"".join(b"\x00" + bytes(c for x in range(w * scale) for c in ((215, 240, 255) if px[x // scale, y // scale] else (11, 18, 32))) for y in range(h * scale))

  def chunk(t, d):
    return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
  open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 2, 0, 0, 0))
                         + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def main():
  preview = sys.argv[1] if len(sys.argv) > 1 else None
  lines = ['"""Logo bitmaps for the OLED, MONO_HLSB (w, h, bytes). Generated by',
           'tools/gen-logos.py from tools/logos/*.png and docs/logo.png; do not edit."""', ""]
  for name, src, box, mode, crop in JOBS:
    im = Image.open(src).convert("RGBA")
    im = Image.alpha_composite(Image.new("RGBA", im.size, (255, 255, 255, 255)), im)
    if crop:
      w, h = im.size
      im = im.crop((int(crop[0] * w), int(crop[1] * h), int(crop[2] * w), int(crop[3] * h)))
    mask = fit(im.convert("RGB"), box, mode)
    w, h, buf = hlsb(mask)
    lines.append("%s = (%d, %d, %r)" % (name, w, h, buf))
    lines.append("")
    if preview:
      png(os.path.join(preview, "logo-%s.png" % name.lower()), mask)
    print("%s: %dx%d, %d bytes" % (name, w, h, len(buf)))
  with open(OUT, "w") as f:
    f.write("\n".join(lines))


main()
